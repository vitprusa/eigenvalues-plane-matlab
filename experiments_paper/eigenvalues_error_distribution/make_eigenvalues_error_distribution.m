function make_eigenvalues_error_distribution(n_eigenvalues, name)
%MAKE_EIGENVALUES_ERROR_DISTRIBUTION Where in the spectrum each method's error sits.
%
%   make_eigenvalues_error_distribution() plots the relative error of every one
%   of the first n eigenvalues against its index, for DST, finite differences and
%   finite elements, all three at the same moderate resolution. The default is
%   n = 1000 on the L-shaped domain.
%
%   make_eigenvalues_error_distribution(n, name) asks for another block size or
%   another domain.
%
%   The question is not how fast a method converges -- MAKE_EIGENVALUES_-
%   CONVERGENCE_INDEX asks that, one eigenvalue at a time -- nor what a whole
%   block costs, which is COMPUTE_EIGENVALUES_DOF_REQUIREMENT. It is how one
%   run spends its accuracy across the block it returns: whether the error is
%   spread evenly over the spectrum or concentrated at one end of it. A single
%   resolution therefore, and every index of it drawn.
%
%   The resolutions are one level of the sweep in MAKE_EIGENVALUES_CONVERGENCE_-
%   INDEX, chosen so that the three methods carry as nearly the same number of
%   degrees of freedom as that sweep allows -- on the L-shape, 2241 for DST and
%   FD at M = 55 and 2257 for FEM at Hmax = 0.0755, a spread of 0.7 per cent.
%   Without that the figure would compare resolutions rather than methods. The
%   dof count in the file names is the shared DST/FD one.
%
%   Moderate on purpose: at 2241 degrees of freedom the thousandth eigenvalue
%   sits at 45 per cent of the run's own spectrum, high enough that the methods
%   are visibly working for it and low enough that the run is not the reference.
%
%   Chebyshev collocation does not appear. Its operator is a Kronecker sum of
%   one-dimensional differentiation matrices and so needs a domain filling a
%   tensor-product box, which the L-shape is not; see DOMAIN_CATALOG_CHEB.
%
%   The DST curve is drawn in two parts. A third of this block -- 326 of the
%   first thousand -- are the eigenvalues pi^2*(m^2+n^2) of the three unit
%   squares, whose eigenfunctions vanish on the internal edges and are sine modes
%   of the bounding box exactly. DST returns those to about 1e-12 relative to the
%   closed form at any resolution, so they say nothing about how well it
%   discretises this domain and, drawn together with the rest, swamp it. They are
%   separated out; see IS_SQUARE_MODE. FD and FEM have no such subspace and are
%   drawn whole.
%
%   The reference is a DST run at M_REF, far finer than the runs measured
%   against it, the L-shape having no closed-form spectrum and no published
%   values away from the ground state. What that is worth is not uniform across
%   the figure, and the low-index end is where it is worth least: run and
%   reference are both DST and share whatever the re-entrant corner does to
%   them, so the DST curve there reports agreement between two DST runs rather
%   than distance from the true eigenvalues. The reference itself sits about
%   1e-3 from the published MPS value of lambda_1. Read the DST curve's low-index
%   end as an upper bound on its accuracy and no more; the FD and FEM curves,
%   whose errors are orders of magnitude larger over most of the block, are
%   unaffected.
%
%   Output, into results_paper/eigenvalues_error_distribution/:
%     - <domain>_error_distribution_n<n>_dofs<D>.csv  one row per index, with
%       the reference eigenvalue and each method's eigenvalue and relative
%       error,
%     - <domain>_error_distribution_n<n>_dofs<D>.eps  the relative error against
%       the index, one series of markers per method, the index axis linear,
%     - <domain>_error_distribution_n<n>_dofs<D>_log_log.eps  the same data with
%       a logarithmic index, which the first few indices need and the body of the
%       block does not; see PLOT_DISTRIBUTION, and
%     - <domain>_error_distribution_n<n>_reference-eigenvalues.csv  the
%       reference spectrum. It carries no dof token: it is the same reference
%       whatever resolution the runs are taken at, so several dof levels of one
%       domain share it.
%   Both CSVs are caches: present and complete, they are read rather than
%   recomputed, so a figure-only pass costs nothing. Delete them to force the
%   computation again.
%
%   Requires the PDE Toolbox (FEM).
%
%   See also MAKE_EIGENVALUES_CONVERGENCE_INDEX, which follows one index across
%   resolutions where this follows one resolution across indices, and
%   COMPUTE_EIGENVALUES_DOF_REQUIREMENT, which reduces the same block to its
%   largest error.
%
%   Generated by Claude Code (Claude Opus 5).

    if nargin < 1 || isempty(n_eigenvalues)
        n_eigenvalues = 1000;
    end
    if ~isscalar(n_eigenvalues) || n_eigenvalues < 1 || n_eigenvalues ~= fix(n_eigenvalues)
        error('eigenvalues_error_distribution:count', ...
            'The number of eigenvalues must be a positive whole number, got %g.', ...
            n_eigenvalues);
    end

    here         = fileparts(mfilename('fullpath'));
    project_root = fileparts(fileparts(here));
    run(fullfile(project_root, 'startup.m'));
    addpath(fullfile(project_root, 'experiments'));   % domain_catalog_dst / _fem

    out_dir = fullfile(project_root, 'results_paper', 'eigenvalues_error_distribution');
    if ~exist(out_dir, 'dir')
        mkdir(out_dir);
    end

    cfgs = domain_configs();
    if nargin >= 2 && ~isempty(name)
        known = {cfgs.name};
        cfgs = cfgs(strcmp(known, name));
        if isempty(cfgs)
            error('eigenvalues_error_distribution:unknownDomain', ...
                'Unknown domain "%s" (known: %s).', name, strjoin(known, ', '));
        end
    end

    for i = 1:numel(cfgs)
        cfg = cfgs(i);
        fprintf('=== %s, first %d eigenvalues ===\n', cfg.name, n_eigenvalues);

        ref_csv = fullfile(out_dir, sprintf('%s_error_distribution_n%d_reference-eigenvalues.csv', ...
                                            cfg.name, n_eigenvalues));
        [reference, ref_dofs] = reference_spectrum(cfg, n_eigenvalues, ref_csv);

        stem = fullfile(out_dir, sprintf('%s_error_distribution_n%d_dofs%d', ...
                                         cfg.name, n_eigenvalues, cfg.dofs_label));
        csv = [stem '.csv'];
        runs = compute_runs(cfg, n_eigenvalues, reference, csv, ref_dofs);
        report_runs(runs, reference, n_eigenvalues);
        % Two figures of the same data, differing in the index axis alone; see
        % PLOT_DISTRIBUTION for what each is good for.
        plot_distribution(stem, runs, reference, n_eigenvalues, 'linear');
        plot_distribution([stem '_log_log'], runs, reference, n_eigenvalues, 'log');
    end
end


function cfgs = domain_configs()
%DOMAIN_CONFIGS Geometry, the one resolution per method, and the reference.
%
%   One resolution per method rather than a sweep: this family asks what a
%   single run does across its block. The three are a level of the sweep in
%   MAKE_EIGENVALUES_CONVERGENCE_INDEX, picked where the dof counts of the three
%   methods lie closest together.
%
%   DOFS_LABEL is the count that goes into the file names, the shared DST/FD one;
%   the FEM mesh cannot be made to land on it exactly and comes within a per
%   cent, which the CSV header records run by run.
    cfgs = struct('name', {}, 'pretty', {}, 'box', {}, 'phi', {}, ...
                  'gd', {}, 'ns', {}, 'sf', {}, ...
                  'M_run', {}, 'Hmax_fem', {}, 'M_ref', {}, 'dofs_label', {});

    % --- L-shaped domain ----------------------------------------------------
    % Box [-1,1]^2, so h = 2/(M+1) and M+1 must be even for the re-entrant
    % corner at the origin to fall on a grid line. On this grid
    % dofs = 3*M^2/4 - M/2 exactly, so M = 55 carries 2241 of them; the FEM mesh
    % at Hmax = 0.0755 carries 2257, through the empirical dofs*Hmax^2 ~ 13.6 of
    % this geometry.
    %
    % The reference is the DST run at M = 163, 19845 dofs: the finest grid whose
    % dense eig fits in memory here, about two minutes, and the same reference
    % the convergence and DOF-requirement families use.
    cfgs(end+1) = struct( ...
        'name', 'L_shaped', 'pretty', 'L-shaped', ...
        'box', [-1 1 -1 1], ...
        'phi', @(x, y) indicator_L_shaped(x, y, -1, 0, 1, -1, 0, 1), ...
        'gd', [[3; 4; -1; 1; 1; -1; -1; -1; 1; 1], [3; 4; 0; 1; 1; 0; 0; 0; 1; 1]], ...
        'ns', char('R1', 'R2')', 'sf', 'R1-R2', ...
        'M_run', 55, 'Hmax_fem', 0.0755, 'M_ref', 163, 'dofs_label', 2241);
end


function [reference, ref_dofs] = reference_spectrum(cfg, n, csv)
%REFERENCE_SPECTRUM The first n eigenvalues everything else is measured against.
%
%   The DST run at cfg.M_REF, cached. It is a computation, not a closed form,
%   and what it is worth is discussed in the header: away from the ground state
%   there is nothing published to use instead.
    if exist(csv, 'file')
        [reference, ref_dofs, ref_M] = read_reference_csv(csv, n);
        % The resolution is part of what the cache holds, not just the values: a
        % reference recomputed at another M is a different reference, and every
        % error in the table is measured against it.
        if numel(reference) >= n && ref_M == cfg.M_ref
            fprintf('  reference: %s (%d dofs, cached)\n', csv, ref_dofs);
            reference = reference(1:n);
            return;
        end
        if ref_M ~= cfg.M_ref
            fprintf('  reference: cached at M = %d, wanted at M = %d, recomputing\n', ...
                    ref_M, cfg.M_ref);
        end
    end

    [x_range, y_range] = bounding_box(cfg.box(1), cfg.box(2), cfg.box(3), cfg.box(4));
    fprintf('  reference: DST at M = %d, computing\n', cfg.M_ref);
    t = tic;
    [evals, ref_dofs] = dst_spectrum(x_range, y_range, cfg.M_ref, cfg.phi);
    fprintf('    dofs = %d, lambda_%d = %.9f, time = %.1f s\n', ...
            ref_dofs, n, evals(n), toc(t));
    if numel(evals) < n
        error('eigenvalues_error_distribution:reference', ...
            'The reference run carries %d eigenvalues, %d asked for.', ...
            numel(evals), n);
    end
    write_reference_csv(csv, cfg, evals(1:n), ref_dofs, n);
    reference = evals(1:n);
end


function runs = compute_runs(cfg, n, reference, csv, ref_dofs)
%COMPUTE_RUNS The three runs and their per-index errors, cached as one table.
%
%   The whole table is the cache here rather than run-by-run rows: there are
%   three runs, they cost a few seconds between them at this resolution, and an
%   interruption loses nothing worth keeping.
    if exist(csv, 'file')
        [runs, cached_ref_dofs] = read_runs_csv(csv, n);
        % Every error in the table is measured against one reference; a table
        % written against another cannot be read as this one.
        if ~isempty(runs) && cached_ref_dofs == ref_dofs
            fprintf('  (reading %s)\n', csv);
            return;
        end
        fprintf('  (%s was measured against a different reference: recomputing)\n', csv);
    end

    [x_range, y_range] = bounding_box(cfg.box(1), cfg.box(2), cfg.box(3), cfg.box(4));
    warm_up(cfg, x_range, y_range);

    plan = { ...
        'DST', sprintf('M = %d', cfg.M_run),      @() dst_spectrum(x_range, y_range, cfg.M_run, cfg.phi); ...
        'FD',  sprintf('M = %d', cfg.M_run),      @() fd_spectrum(cfg, cfg.M_run); ...
        'FEM', sprintf('Hmax = %g', cfg.Hmax_fem), @() fem_spectrum(cfg, cfg.Hmax_fem)};

    runs = empty_runs();
    for i = 1:size(plan, 1)
        t = tic;
        [evals, dofs] = plan{i, 3}();
        tsec = toc(t);
        if numel(evals) < n
            error('eigenvalues_error_distribution:short', ...
                '%s at %s carries %d eigenvalues, %d asked for.', ...
                plan{i, 1}, plan{i, 2}, numel(evals), n);
        end
        lambda = evals(1:n);
        runs(end+1) = struct('method', plan{i, 1}, 'resolution', plan{i, 2}, ...
            'dofs', dofs, 'lambda', lambda, ...
            'rel_err', abs(lambda - reference) ./ reference, ...
            'time', tsec); %#ok<AGROW>
        fprintf('  %-4s %-14s dofs = %-6d time = %6.2f s\n', ...
                plan{i, 1}, plan{i, 2}, dofs, tsec);
    end
    write_runs_csv(csv, cfg, runs, reference, n, ref_dofs);
end


function [evals, dofs] = dst_spectrum(x_range, y_range, M, phi)
    [L, info] = make_dst_laplace_mat_batched(x_range, y_range, M, phi);
    evals = sort(-eig(dst_laplace_symmetrise(L)), 'ascend');
    dofs = info.dofs;
end


function [evals, dofs] = fd_spectrum(cfg, M)
    [evals, info] = fd_laplace_spectrum(struct('box', cfg.box, 'phi', cfg.phi, 'M', M));
    evals = sort(real(evals(:)), 'ascend');
    dofs = info.dofs;
end


function [evals, dofs] = fem_spectrum(cfg, h)
    entry = struct('gd', cfg.gd, 'ns', cfg.ns, 'sf', cfg.sf, ...
                   'Hmax_eig', h, 'Hmax_solvepdeeig', h);
    [evals, info] = fem_laplace_spectrum(entry, "eig");
    evals = sort(real(evals(:)), 'ascend');
    dofs = info.dofs;
end


function warm_up(cfg, x_range, y_range)
%WARM_UP Discarded runs of each method, so the timings are of the work.
%
%   MATLAB's toolbox load and JIT compilation are paid once per session and
%   would otherwise land on whichever run happens to go first. Reached only when
%   something is to be computed, so a figure-only pass stays free.
    fprintf('  warm-up: DST, FD, FEM (discarded)\n');
    entry = struct('gd', cfg.gd, 'ns', cfg.ns, 'sf', cfg.sf, ...
                   'Hmax_eig', 0.33, 'Hmax_solvepdeeig', 0.33);
    for i = 1:2
        L = make_dst_laplace_mat_batched(x_range, y_range, 13, cfg.phi);
        eig(dst_laplace_symmetrise(L));
        fd_laplace_spectrum(struct('box', cfg.box, 'phi', cfg.phi, 'M', 13));
        fem_laplace_spectrum(entry, "eig");
    end
end


function report_runs(runs, reference, n)
%REPORT_RUNS The error at a few indices, printed, as the figure's headline.
%
%   The DST row is given twice, once over the square modes and once over the
%   rest, for the reason in IS_SQUARE_MODE: the two are different quantities and
%   an average over both describes neither.
    probes = unique([1 10 100 round(n/2) n]);
    probes = probes(probes <= n);
    square = square_mask(runs, reference);

    fprintf('\n    %-22s %8s', 'method', 'dofs');
    for k = probes
        fprintf(' %10s', sprintf('k = %d', k));
    end
    fprintf('\n');
    for i = 1:numel(runs)
        fprintf('    %-22s %8d', runs(i).method, runs(i).dofs);
        fprintf(' %10.2e', runs(i).rel_err(probes));
        fprintf('\n');
    end

    hit = find(strcmp({runs.method}, 'DST'), 1);
    if ~isempty(hit)
        n_ref = sum(is_square_mode(reference));
        fprintf('\n    %d of the first %d eigenvalues are pi^2*(m^2+n^2).', n_ref, n);
        fprintf(' At the %d indices where\n    the run and the reference sort them alike,', ...
                sum(square));
        fprintf(' DST is within %.1e;\n    over the rest of the block it is within %.1e.\n', ...
                max(runs(hit).rel_err(square)), max(runs(hit).rel_err(~square)));
        if n_ref > sum(square)
            fprintf(['    The other %d are drawn with the rest: a neighbouring ', ...
                     'eigenvalue crosses\n    them in the ordering, so the ', ...
                     'comparison there pairs unlike eigenvalues.\n'], ...
                    n_ref - sum(square));
        end
    end
    fprintf('\n');
end


function tf = square_mask(runs, reference)
%SQUARE_MASK The indices where run and reference agree the eigenvalue is exact.
%
%   Both lists, not the reference alone. The two are sorted ascending and
%   compared index by index, and that pairing can go wrong exactly here: a
%   neighbouring eigenvalue that DST resolves only to about 1e-4 crosses an
%   exactly represented one in the ordering, and the run's k-th entry is then a
%   different eigenvalue from the reference's k-th. At 2241 degrees of freedom
%   this happens at six of the 326 square indices of the first thousand.
%
%   Marking those by the reference alone would put a filled marker on an index
%   whose plotted value is the distance between two unlike eigenvalues -- a
%   genuine mismatch of order 1e-4, and nothing to do with how well DST returns
%   the exact ones. Requiring both to agree puts them among the open markers,
%   where they belong: the filled population is then exactly the set of indices
%   at which DST returned the eigenvalue the reference has, which is what the
%   legend claims of it.
%
%   Nothing is dropped either way. The six points stay on the figure; what
%   changes is which population they are counted in.
%
%   Degeneracy makes a crossing likelier -- five of the six sit at a double
%   eigenvalue, where the neighbour has only one gap to beat -- but what drives
%   it is the size of DST's error on the neighbour, not the degeneracy.
    hit = find(strcmp({runs.method}, 'DST'), 1);
    if isempty(hit)
        tf = false(numel(reference), 1);
        return;
    end
    tf = is_square_mode(reference) & is_square_mode(runs(hit).lambda);
end


function tf = is_square_mode(lambda)
%IS_SQUARE_MODE Which eigenvalues the sine basis represents exactly.
%
%   The L-shape is three unit squares, and the eigenfunctions vanishing on the
%   two internal edges are the square's own, sin(m*pi*x)*sin(n*pi*y) on each
%   piece, with eigenvalue pi^2*(m^2+n^2) known in closed form. On the bounding
%   box [-1,1]^2 those are sine modes of even index, so the DST operator carries
%   them exactly and returns their eigenvalues at any resolution: 326 of the
%   first thousand here, every one of them reproduced at 2241 degrees of freedom
%   to within 4.3e-12 relative and with the right multiplicity, and that against
%   the closed form itself rather than merely in agreement with the reference.
%
%   They are therefore not a measure of how well DST discretises this domain,
%   and drawn in one series with the rest they swamp it -- the error swings
%   twelve decades between neighbouring indices and fills the axes. The figure
%   draws them apart; SQUARE_MASK says which indices those are.
%
%   Recognised by the eigenvalue rather than tracked through the geometry:
%   lambda/pi^2 a whole number. The tolerance is loose against the 1e-12 that the
%   computation achieves on them and tight against the spacing of the spectrum in
%   these units, which is of order a tenth.
    ratio = lambda(:) / pi^2;
    tf = abs(ratio - round(ratio)) < 1e-6;
end


function runs = empty_runs()
    runs = struct('method', {}, 'resolution', {}, 'dofs', {}, 'lambda', {}, ...
                  'rel_err', {}, 'time', {});
end


function write_reference_csv(csv, cfg, evals, dofs, n)
    fid = fopen(csv, 'w');
    if fid == -1
        error('eigenvalues_error_distribution:csv', 'Could not open %s for writing.', csv);
    end
    closer = onCleanup(@() fclose(fid));
    fprintf(fid, '# Domain: %s (DST, dense eig full spectrum)\n', cfg.name);
    fprintf(fid, '# Reference for the error distribution of the first %d eigenvalues\n', n);
    fprintf(fid, '# Resolution M = %d, dofs = %d\n', cfg.M_ref, dofs);
    fprintf(fid, 'n,lambda_n\n');
    fprintf(fid, '%d,%.17g\n', [1:numel(evals); reshape(evals, 1, [])]);
end


function [evals, dofs, M] = read_reference_csv(csv, n)
    fid = fopen(csv, 'r');
    if fid == -1
        error('eigenvalues_error_distribution:csvread', 'Could not open %s.', csv);
    end
    closer = onCleanup(@() fclose(fid));
    evals = zeros(n, 1);
    count = 0; dofs = NaN; M = NaN;
    while true
        line = fgetl(fid);
        if ~ischar(line); break; end
        s = strtrim(line);
        if isempty(s); continue; end
        if s(1) == '#'
            tok = regexp(s, 'dofs\s*=\s*(\d+)', 'tokens', 'once');
            if ~isempty(tok); dofs = str2double(tok{1}); end
            tok = regexp(s, 'M\s*=\s*(\d+)', 'tokens', 'once');
            if ~isempty(tok); M = str2double(tok{1}); end
            continue;
        end
        if strncmpi(s, 'n,', 2); continue; end
        p = strsplit(s, ',');
        if numel(p) < 2; continue; end
        count = count + 1;
        if count <= n
            evals(count) = str2double(p{2});
        end
    end
    evals = evals(1:min(count, n));
end


function write_runs_csv(csv, cfg, runs, reference, n, ref_dofs)
%WRITE_RUNS_CSV One row per index: the reference, then each method's value and error.
%
%   Seventeen significant digits: the CSV is what the figure is redrawn from, so
%   it has to carry a double back exactly.
    fid = fopen(csv, 'w');
    if fid == -1
        error('eigenvalues_error_distribution:csv', 'Could not open %s for writing.', csv);
    end
    closer = onCleanup(@() fclose(fid));
    fprintf(fid, ['# Domain: %s (relative error of each of the first %d ', ...
                  'eigenvalues against its index, dense eig)\n'], cfg.name, n);
    fprintf(fid, '# Reference: DST at M = %d, dofs = %d\n', cfg.M_ref, ref_dofs);
    for i = 1:numel(runs)
        fprintf(fid, '# %s: %s, dofs = %d, time = %.4f s\n', ...
                runs(i).method, runs(i).resolution, runs(i).dofs, runs(i).time);
    end
    fprintf(fid, 'k,lambda_ref');
    for i = 1:numel(runs)
        fprintf(fid, ',lambda_%s,rel_error_%s', runs(i).method, runs(i).method);
    end
    fprintf(fid, '\n');
    block = zeros(2 * numel(runs) + 2, n);
    block(1, :) = 1:n;
    block(2, :) = reference;
    for i = 1:numel(runs)
        block(2 * i + 1, :) = runs(i).lambda;
        block(2 * i + 2, :) = runs(i).rel_err;
    end
    fmt = ['%d,%.17g', repmat(',%.17g', 1, 2 * numel(runs)), '\n'];
    fprintf(fid, fmt, block);
end


function [runs, ref_dofs] = read_runs_csv(csv, n)
%READ_RUNS_CSV Read back a table written by WRITE_RUNS_CSV.
%
%   A table shorter than the block asked for is no use, and comes back empty so
%   that the caller recomputes rather than drawing a truncated figure.
    runs = empty_runs();
    ref_dofs = NaN;
    methods = {}; dofs = []; resolutions = {}; times = [];
    fid = fopen(csv, 'r');
    if fid == -1
        return;
    end
    closer = onCleanup(@() fclose(fid));
    while true
        line = fgetl(fid);
        if ~ischar(line) || isempty(line) || line(1) ~= '#'; break; end
        tok = regexp(line, '^#\s*Reference:.*dofs\s*=\s*(\d+)', 'tokens', 'once');
        if ~isempty(tok)
            ref_dofs = str2double(tok{1});
            continue;
        end
        tok = regexp(line, '^#\s*(\w+):\s*(.+?),\s*dofs\s*=\s*(\d+),\s*time\s*=\s*([0-9.eE+-]+)', ...
                     'tokens', 'once');
        if ~isempty(tok)
            methods{end+1}     = tok{1}; %#ok<AGROW>
            resolutions{end+1} = tok{2}; %#ok<AGROW>
            dofs(end+1)        = str2double(tok{3}); %#ok<AGROW>
            times(end+1)       = str2double(tok{4}); %#ok<AGROW>
        end
    end
    clear closer;
    try
        t = readtable(csv, 'CommentStyle', '#');
    catch
        return;
    end
    if height(t) < n || isempty(methods)
        return;
    end
    for i = 1:numel(methods)
        runs(end+1) = struct('method', methods{i}, 'resolution', resolutions{i}, ...
            'dofs', dofs(i), 'lambda', t.(sprintf('lambda_%s', methods{i}))(1:n), ...
            'rel_err', t.(sprintf('rel_error_%s', methods{i}))(1:n), ...
            'time', times(i)); %#ok<AGROW>
    end
end


function plot_distribution(stem, runs, reference, n, x_scale)
%PLOT_DISTRIBUTION Relative error against eigenvalue index, one series per method.
%
%   X_SCALE picks the index axis, and the two are kept because neither shows
%   what the other does. Linear gives the body of the block the room it
%   deserves: most of the thousand eigenvalues live in the last decade, which a
%   logarithmic index squeezes into the right-hand quarter, and it is there that
%   FD and FEM separate and rejoin. Logarithmic opens out the first few indices,
%   which a linear axis presses against the left edge, and that is where DST is
%   at its worst -- at the ground state it is beaten by both of the others, the
%   re-entrant corner costing it more than it costs them. The file with the
%   plain name is the linear one; the logarithmic one takes the _log_log suffix.
%
%   The error is logarithmic either way, the three methods being orders of
%   magnitude apart over most of the block.
%
%   Markers and no connecting lines. The quantity is one number per eigenvalue
%   and neighbouring indices are not a curve: adjacent eigenvalues belong to
%   unrelated eigenfunctions, and a line drawn through them invites the eye to
%   read a trend through what is really a scatter of separate results. It also
%   made the DST series unreadable, its neighbours differing by decades.
%
%   The DST series is drawn in two parts, for the reason in IS_SQUARE_MODE. The
%   eigenvalues the sine basis represents exactly -- a third of this block -- are
%   returned to roundoff whatever the resolution, and drawn together with the
%   rest they swamp them. The dot keeps them apart from the open circle of the
%   indices where DST is actually discretising something. FD and FEM get no such
%   split, having no such subspace.
%
%   Colours and markers are those of the convergence and DOF-requirement figures,
%   so that the figures of a domain read as one family. No title, as elsewhere in
%   experiments_paper: the domain is carried by the file name and the caption.
    styles = struct( ...
        'name',   {'DST', 'FD', 'FEM'}, ...
        'color',  {[0 0.45 0.74], [0.85 0.33 0.10], [0.47 0.67 0.19]}, ...
        'marker', {'o', 's', '^'});
    square = square_mask(runs, reference);

    % Render all text with the LaTeX interpreter, as in the other paper figures.
    fig = figure('Visible', 'off', 'Position', [100 100 950 680], ...
        'defaultAxesTickLabelInterpreter', 'latex', ...
        'defaultTextInterpreter',          'latex', ...
        'defaultLegendInterpreter',        'latex');
    ax = axes(fig);
    hold(ax, 'on');

    k = (1:n)';
    for si = 1:numel(styles)
        hit = find(strcmp({runs.method}, styles(si).name), 1);
        if isempty(hit); continue; end
        % A run landing on the reference exactly has no place on a log axis;
        % drawn on the floor instead, as the convergence figures do it.
        err = max(runs(hit).rel_err, eps);
        if strcmp(styles(si).name, 'DST')
            % Both halves name the condition rather than one of them being
            % "DST" plain: the circles cover the complement, not the whole run,
            % and a legend that says so needs no caption to be read.
            plot(ax, k(~square), err(~square), styles(si).marker, ...
                'Color', styles(si).color, 'MarkerSize', 3, ...
                'DisplayName', sprintf(['$\\mathtt{%s}$ ($\\mathtt{DOF}$ = %d), ', ...
                                        '$\\lambda_k \\neq \\pi^2(m^2+n^2)$'], ...
                                       styles(si).name, runs(hit).dofs));
            plot(ax, k(square), err(square), '.', 'Color', styles(si).color, ...
                'MarkerSize', 6, ...
                'DisplayName', sprintf(['$\\mathtt{%s}$ ($\\mathtt{DOF}$ = %d), ', ...
                                        '$\\lambda_k = \\pi^2(m^2+n^2)$'], ...
                                       styles(si).name, runs(hit).dofs));
        else
            plot(ax, k, err, styles(si).marker, 'Color', styles(si).color, ...
                'MarkerSize', 3, ...
                'DisplayName', sprintf('$\\mathtt{%s}$ ($\\mathtt{DOF}$ = %d)', ...
                                       styles(si).name, runs(hit).dofs));
        end
    end

    hold(ax, 'off');
    set(ax, 'XScale', x_scale, 'YScale', 'log');
    % A logarithmic index cannot start at nought, and a linear one gains nothing
    % by starting at one.
    if strcmp(x_scale, 'log')
        xlim(ax, [1 n]);
    else
        xlim(ax, [0 n]);
    end
    xlabel(ax, 'eigenvalue index $k$');
    % A built fraction rather than a solidus, as in the sibling families, and set
    % a size larger since numerator and denominator are rendered small.
    ylabel(ax, ['$\frac{|\lambda_k - \lambda_k^{\mathtt{DST}}|}', ...
                '{\lambda_k^{\mathtt{DST}}}$'], 'FontSize', 16);
    % The corner the three populations leave free moves with the index axis, so
    % the placement follows it. Linear: FD and FEM rise steeply out of the
    % left-hand corner and fill the top, and what is left is the middle band, so
    % east. Logarithmic: that same rise is spread across the width and the free
    % corner is the bottom left, where the square modes are still sparse at low
    % index.
    if strcmp(x_scale, 'log')
        legend_location = 'southwest';
    else
        legend_location = 'east';
    end
    legend(ax, 'Location', legend_location, 'FontSize', 10, 'Box', 'off');
    grid(ax, 'on'); box(ax, 'on');
    set(ax, 'FontSize', 12);

    save_figure(fig, stem);
end


function save_figure(fig, stem)
%SAVE_FIGURE One figure as vector EPS, then close it.
%
%   Line art -- axes, three curves, a legend -- so a vector figure is smaller
%   than a raster of the same page area and sharp at any size. Read by
%   latex/dvips directly, and by pdflatex through epstopdf.
    eps_file = [stem '.eps'];
    try
        exportgraphics(fig, eps_file, 'ContentType', 'vector');
    catch
        print(fig, eps_file, '-depsc2', '-vector');
    end
    fprintf('  Wrote %s\n', eps_file);
    close(fig);
end
