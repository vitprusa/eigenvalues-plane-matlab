function eigenvalues_rectangle_order(M, margin)
%EIGENVALUES_RECTANGLE_ORDER Lattice of analytic-eigenvalue positions for the rectangle.
%
%   eigenvalues_rectangle_order()         uses M = 19 and a default table margin.
%   eigenvalues_rectangle_order(M)        uses resolution M.
%   eigenvalues_rectangle_order(M, margin) extends the analytic (m, n) table
%                                          margin indices past the resolved
%                                          modes in each direction.
%
%   Companion to EIGENVALUES_RECTANGLE_MATCH. Same set-up: the Dirichlet-
%   Laplacian on the 2:1 catalog rectangle [0, 2*pi] x [0, pi] has the exact
%   eigenvalues
%
%       lambda_{m,n} = (m*pi/Lx)^2 + (n*pi/Ly)^2 = m^2/4 + n^2,   m, n = 1, 2, ...
%
%   This script
%     1. computes the full DST spectrum at resolution M
%        (make_dst_laplace_mat_batched + eig),
%     2. builds the analytic lattice lambda_{m,n} indexed by m (rows, x-modes)
%        and n (columns, y-modes), and matches every computed eigenvalue to a
%        lattice cell, then
%     3. orders the analytic eigenvalues by magnitude and replaces each lattice
%        entry with its POSITION (rank, 1 = smallest) in that ordered sequence.
%
%   Cells matched to a computed eigenvalue are shown in bold and the rest in
%   normal weight. Because the DST grid resolves a rectangular Mx-by-My block
%   of modes rather than the leading eigenvalues, the bold cells are NOT
%   positions 1..Mx*My: some unresolved border modes have smaller eigenvalues
%   than some resolved ones and so take lower positions. That mismatch between
%   "resolved" and "leading" is exactly what the position lattice exposes.
%
%   Positions are ranked over a lattice large enough to contain every analytic
%   eigenvalue up to the largest one displayed, so each shown position is
%   correct against the full spectrum, not just the table window.
%
%   With equal grid spacing in x and y, the top edge y = pi only lands on a
%   grid line when M+1 is even, i.e. M is odd; the default M = 19 is the odd
%   value closest to 20. The grid then resolves Mx = M modes in x and
%   My = (M+1)/2 - 1 modes in y. Change Lx, Ly below for another rectangle
%   (and pick M so both edges stay on the grid).
%
%   See also EIGENVALUES_RECTANGLE_MATCH, MAKE_DST_LAPLACE_MAT_BATCHED,
%   DOMAIN_CATALOG_DST.
%
%   Generated by Claude (Claude Opus 4.8, model ID claude-opus-4-8).

    if nargin < 1 || isempty(M)
        M = 19;
    end
    if nargin < 2 || isempty(margin)
        margin = 4;     % how far the analytic table reaches past the modes
    end

    % This file lives in experiments/; put the project sources on the path.
    experiments_dir = fileparts(mfilename('fullpath'));
    project_root    = fileparts(experiments_dir);
    run(fullfile(project_root, 'startup.m'));

    % 2:1 catalog rectangle [0, Lx] x [0, Ly]. Analytic spectrum is
    % lambda_{m,n} = (m*pi/Lx)^2 + (n*pi/Ly)^2 = m^2/4 + n^2.
    Lx = 2 * pi;
    Ly = pi;

    % --- 1. Computed full spectrum at resolution M -----------------------
    [x_range, y_range] = bounding_box(0, Lx, 0, Ly);
    phi = @(x, y) indicator_rectangle(x, y, 0, Lx, 0, Ly);
    [L, info] = make_dst_laplace_mat_batched(x_range, y_range, M, phi);
    lambda_num = sort(-real(eig(L)), 'ascend');   % positive, ascending

    % Modes resolved per direction = interior grid points per direction. For a
    % rectangle filling its box this is the full grid minus the two boundary
    % lines. Guard against a domain whose edges miss the grid.
    Mx = numel(info.x_vec) - 2;
    My = numel(info.y_vec) - 2;
    if Mx * My ~= info.dofs
        error('eigenvalues_rectangle_order:misaligned', ...
            ['Grid does not cleanly resolve the rectangle (Mx*My = %d, ', ...
             'dofs = %d). Pick M so both edges land on grid lines ', ...
             '(M odd for the 2:1 rectangle).'], Mx * My, info.dofs);
    end

    fprintf('Rectangle [0, %.4f] x [0, %.4f], M = %d, dofs = %d (Mx = %d, My = %d)\n', ...
        Lx, Ly, M, info.dofs, Mx, My);

    % --- 2. Analytic eigenvalue lattice indexed by (m, n) ---------------
    mm = (1:(Mx + margin))';
    nn = (1:(My + margin));
    lambda_tab = (mm * pi / Lx).^2 + (nn * pi / Ly).^2;

    % --- 3. Match computed eigenvalues to lattice cells -----------------
    % Greedy, multiplicity-aware matching by value; resolved cells (m <= Mx,
    % n <= My) are visited first so they claim their computed eigenvalue ahead
    % of any coincident out-of-grid cell of equal value.
    cell_val = lambda_tab(:);
    in_grid  = false(numel(mm), numel(nn));
    in_grid(1:Mx, 1:My) = true;
    order    = [find(in_grid(:)); find(~in_grid(:))];

    reltol  = 1e-6;
    used    = false(numel(lambda_num), 1);
    matched = false(numel(mm), numel(nn));
    for c = order'
        target = cell_val(c);
        cand = find(~used & abs(lambda_num - target) <= reltol * target, 1);
        if ~isempty(cand)
            used(cand)  = true;
            matched(c)  = true;
        end
    end
    n_matched   = nnz(matched);
    n_unmatched = nnz(~used);

    % --- 4. Replace each eigenvalue by its position in the ordered list -
    rank_tab = eigenvalue_positions(lambda_tab, Lx, Ly);

    meta = struct('Lx', Lx, 'Ly', Ly, 'M', M, 'dofs', info.dofs, ...
        'Mx', Mx, 'My', My, 'n_matched', n_matched, ...
        'n_cells', numel(matched), 'n_computed', numel(lambda_num), ...
        'n_unmatched', n_unmatched);

    % --- 5. Print the position lattice, matched cells in bold -----------
    fprintf('\nPosition of lambda_{m,n} in the magnitude-ordered sequence:\n');
    print_table(rank_tab, matched, mm, nn, '%9d');
    fprintf('\nMatched %d of %d lattice cells to computed eigenvalues.\n', ...
        n_matched, numel(matched));
    fprintf('Computed eigenvalues: %d total, %d unmatched.\n', ...
        numel(lambda_num), n_unmatched);
    if n_unmatched > 0
        warning('eigenvalues_rectangle_order:unmatched', ...
            ['%d computed eigenvalues did not match any (m, n) cell; ', ...
             'increase margin so the lattice covers all resolved modes.'], ...
            n_unmatched);
    end

    % --- 6. Save the position lattice to results/ as markdown -----------
    out_dir = fullfile(project_root, 'results', 'eigenvalues_rectangle_order');
    if ~exist(out_dir, 'dir')
        mkdir(out_dir);
    end
    md_file = fullfile(out_dir, sprintf('rectangle_order_M%d.md', M));
    write_markdown(md_file, rank_tab, matched, mm, nn, meta);
    fprintf('Wrote %s\n', md_file);
end


function rank_tab = eigenvalue_positions(lambda_tab, Lx, Ly)
%EIGENVALUE_POSITIONS Position of each lattice cell in the magnitude-ordered spectrum.
%   Returns a matrix the size of lambda_tab whose (r, c) entry is the rank of
%   lambda_{m,n} (1 = smallest) among ALL analytic eigenvalues, not just those
%   in the table. To get that right at the high end of the table, the ranking
%   lattice is grown until it contains every (m, n) whose eigenvalue does not
%   exceed the largest one displayed: since lambda >= (m*pi/Lx)^2 and
%   lambda >= (n*pi/Ly)^2, any such mode has m <= (Lx/pi)*sqrt(thr) and
%   n <= (Ly/pi)*sqrt(thr).
    [nrow, ncol] = size(lambda_tab);
    thr = lambda_tab(nrow, ncol);                 % largest displayed eigenvalue
    Mrank = max(nrow, ceil((Lx / pi) * sqrt(thr)) + 1);
    Nrank = max(ncol, ceil((Ly / pi) * sqrt(thr)) + 1);

    [Mr, Nr] = ndgrid(1:Mrank, 1:Nrank);
    val = (Mr * pi / Lx).^2 + (Nr * pi / Ly).^2;

    % Sort by magnitude; round first so genuinely degenerate eigenvalues tie
    % exactly (the smallest spacing here is 1/4), then break ties by (m, n) for
    % a deterministic sequence. Position = index in that sequence.
    keys = [round(val(:), 9), Mr(:), Nr(:)];
    [~, ord] = sortrows(keys);
    pos = zeros(Mrank * Nrank, 1);
    pos(ord) = 1:numel(ord);
    pos = reshape(pos, Mrank, Nrank);

    rank_tab = pos(1:nrow, 1:ncol);
end


function print_table(data, matched, mm, nn, fmt)
%PRINT_TABLE Print data indexed by m (rows) and n (cols); matched cells bold.
%   fmt is the printf format for one cell (e.g. '%9d'); its field width sets
%   the column width.
    BOLD  = [char(27) '[1m'];
    RESET = [char(27) '[0m'];

    field = sscanf(fmt, '%%%d');            % numeric field width from the format
    label = 6;                              % width of the row-label column

    % Header: n indices across the top.
    fprintf('%*s |', label, 'm \ n');
    for n = nn
        fprintf('%*d', field, n);
    end
    fprintf('\n');
    fprintf('%s\n', repmat('-', 1, label + 2 + field * numel(nn)));

    % One row per m.
    for r = 1:numel(mm)
        fprintf('%*d |', label, mm(r));
        for c = 1:numel(nn)
            cell = sprintf(fmt, data(r, c));
            if matched(r, c)
                fprintf('%s%s%s', BOLD, cell, RESET);
            else
                fprintf('%s', cell);
            end
        end
        fprintf('\n');
    end
end


function write_markdown(md_file, rank_tab, matched, mm, nn, meta)
%WRITE_MARKDOWN Write the (m, n) position lattice as markdown; matched in bold.
%   Matched cells are wrapped in **...** so they render bold, mirroring the
%   terminal output of PRINT_TABLE.
    fid = fopen(md_file, 'w');
    if fid == -1
        error('eigenvalues_rectangle_order:cannotOpen', ...
            'Could not open %s for writing.', md_file);
    end
    closer = onCleanup(@() fclose(fid));

    fprintf(fid, '# Rectangle DST eigenvalue ordering\n\n');
    fprintf(fid, ['Full DST-Laplacian spectrum of the rectangle ', ...
        '$[0, %.4f] \\times [0, %.4f]$ at resolution $M = %d$ (dofs $= %d$). ', ...
        'Each cell holds the **position** of the analytic eigenvalue ', ...
        '$\\lambda_{m,n} = (m\\pi/L_x)^2 + (n\\pi/L_y)^2 = m^2/4 + n^2$ in the ', ...
        'magnitude-ordered sequence of all analytic eigenvalues (1 = smallest).\n\n'], ...
        meta.Lx, meta.Ly, meta.M, meta.dofs);
    fprintf(fid, ['The grid resolves $M_x = %d$ modes in $x$ and ', ...
        '$M_y = %d$ modes in $y$. Cells matched to a computed eigenvalue ', ...
        '(to round-off) are shown in **bold**; the unresolved border ', ...
        '($m > M_x$ or $n > M_y$) is in normal weight. Rows are indexed by ', ...
        '$m$, columns by $n$. The bold cells are not positions $1 \\dots ', ...
        'M_x M_y$: some unresolved border modes outrank resolved ones.\n\n'], ...
        meta.Mx, meta.My);

    % Header row: n indices.
    fprintf(fid, '| $m \\backslash n$ |');
    for n = nn
        fprintf(fid, ' %d |', n);
    end
    fprintf(fid, '\n');

    % Alignment row: left-aligned label column, right-aligned value columns.
    fprintf(fid, '|---|');
    for c = 1:numel(nn)
        fprintf(fid, '--:|');
    end
    fprintf(fid, '\n');

    % One row per m.
    for r = 1:numel(mm)
        fprintf(fid, '| %d |', mm(r));
        for c = 1:numel(nn)
            if matched(r, c)
                fprintf(fid, ' **%d** |', rank_tab(r, c));
            else
                fprintf(fid, ' %d |', rank_tab(r, c));
            end
        end
        fprintf(fid, '\n');
    end

    fprintf(fid, ['\nMatched %d of %d lattice cells to computed eigenvalues. ', ...
        'Computed eigenvalues: %d total, %d unmatched.\n'], ...
        meta.n_matched, meta.n_cells, meta.n_computed, meta.n_unmatched);
end
