function eigenvalues_rectangle_match(M, margin)
%EIGENVALUES_RECTANGLE_MATCH Match the DST rectangle spectrum to the analytic lattice.
%
%   eigenvalues_rectangle_match()         uses M = 19 and a default table margin.
%   eigenvalues_rectangle_match(M)        uses resolution M.
%   eigenvalues_rectangle_match(M, margin) extends the analytic (m, n) table
%                                          margin indices past the resolved
%                                          modes in each direction.
%
%   The Dirichlet-Laplacian on the rectangle [0, Lx] x [0, Ly] has the exact
%   eigenvalues
%
%       lambda_{m,n} = (m*pi/Lx)^2 + (n*pi/Ly)^2,   m, n = 1, 2, ...
%
%   This script
%     1. computes the full DST spectrum at resolution M
%        (make_dst_laplace_mat_batched + eig),
%     2. tabulates the analytic eigenvalues lambda_{m,n} on a grid indexed by
%        m (rows, x-modes) and n (columns, y-modes), and
%     3. matches every computed eigenvalue to a table cell and prints the
%        table with the matched cells in bold and the unmatched cells in the
%        normal weight.
%
%   The DST second-derivative is spectrally exact for the sine modes, so the
%   grid resolves Mx modes in x and My modes in y (the interior point counts
%   of the grid). Every (m, n) with m <= Mx and n <= My is reproduced to
%   round-off and the Mx-by-My sub-block prints bold; the surrounding border
%   (m > Mx or n > My, which the grid does not resolve) prints normal. Any
%   computed eigenvalue that fails to match would also surface here.
%
%   The domain is the 2:1 catalog rectangle [0, 2*pi] x [0, pi]
%   (lambda_{m,n} = m^2/4 + n^2). With equal grid spacing in x and y, the top
%   edge y = pi only lands on a grid line when M+1 is even, i.e. M is odd; the
%   default M = 19 is the odd value closest to 20. The grid then resolves
%   Mx = M modes in x and My = (M+1)/2 - 1 modes in y. Change Lx, Ly below for
%   another rectangle (and pick M so both edges stay on the grid).
%
%   See also MAKE_DST_LAPLACE_MAT_BATCHED, DOMAIN_CATALOG_DST,
%   PLOT_WEYL_ASYMPTOTICS.
%
%   Generated by Claude (Claude Opus 4.8, model ID claude-opus-4-8).

    if nargin < 1 || isempty(M)
        M = 19;
    end
    if nargin < 2 || isempty(margin)
        margin = 11;    % table reaches Mx+margin = 30 rows past the resolved modes
    end

    % This file lives in experiments/eigenvalues_indexing/; put the project
    % sources on the path.
    script_dir      = fileparts(mfilename('fullpath'));
    experiments_dir = fileparts(script_dir);
    project_root    = fileparts(experiments_dir);
    run(fullfile(project_root, 'startup.m'));

    % 2:1 catalog rectangle [0, Lx] x [0, Ly]. Analytic spectrum is
    % lambda_{m,n} = (m*pi/Lx)^2 + (n*pi/Ly)^2 = m^2/4 + n^2.
    Lx = 2 * pi;
    Ly = pi;

    % --- 1. Computed full spectrum at resolution M -----------------------
    [x_range, y_range] = bounding_box(0, Lx, 0, Ly);
    phi = @(x, y) indicator_rectangle(x, y, 0, Lx, 0, Ly);
    [L, info] = make_dst_laplace_mat_batched(x_range, y_range, M, phi);
    % lambda_num = sort(-real(eig(L)), 'ascend');   % positive, ascending
    % positive, ascending
    lambda_num = sort(-eig(dst_laplace_symmetrise(L)), 'ascend');

    % Modes resolved per direction = interior grid points per direction. For a
    % rectangle filling its box this is the full grid minus the two boundary
    % lines. Guard against a domain whose edges miss the grid (the box would
    % then not be cleanly partitioned and dofs ~= Mx*My).
    Mx = numel(info.x_vec) - 2;
    My = numel(info.y_vec) - 2;
    if Mx * My ~= info.dofs
        error('eigenvalues_rectangle_match:misaligned', ...
            ['Grid does not cleanly resolve the rectangle (Mx*My = %d, ', ...
             'dofs = %d). Pick M so both edges land on grid lines ', ...
             '(M odd for the 2:1 rectangle).'], Mx * My, info.dofs);
    end

    fprintf('Rectangle [0, %.4f] x [0, %.4f], M = %d, dofs = %d (Mx = %d, My = %d)\n', ...
        Lx, Ly, M, info.dofs, Mx, My);

    % --- 2. Analytic eigenvalue table indexed by (m, n) -----------------
    % m indexes x-modes (rows), n indexes y-modes (columns); the table reaches
    % margin indices past the resolved Mx, My so the unresolved border shows.
    mm = (1:(Mx + margin))';
    nn = (1:(My + margin));
    lambda_tab = (mm * pi / Lx).^2 + (nn * pi / Ly).^2;   % (Mx+margin)-by-(My+margin)

    % --- 3. Match computed eigenvalues to table cells -------------------
    %
    % Greedy, multiplicity-aware matching by value. Cells the grid actually
    % resolves (m <= Mx, n <= My) are visited first, so they consume their
    % computed eigenvalue before any coincident out-of-grid cell of equal
    % value. Ordering by membership rather than by value also sidesteps the
    % round-off that makes such coincidences differ in the last digits. The
    % result is the clean Mx-by-My bold block.
    cell_val = lambda_tab(:);
    in_grid  = false(numel(mm), numel(nn));
    in_grid(1:Mx, 1:My) = true;
    order    = [find(in_grid(:)); find(~in_grid(:))];

    reltol  = 1e-6;
    used    = false(numel(lambda_num), 1);
    matched = false(numel(mm), numel(nn));

    for c = order'
        target = cell_val(c);
        cand = find(~used & abs(lambda_num - target) <= reltol * target, 1);
        if ~isempty(cand)
            used(cand)  = true;
            matched(c)  = true;
        end
    end

    n_matched   = nnz(matched);
    n_unmatched = nnz(~used);   % computed eigenvalues with no table cell

    meta = struct('Lx', Lx, 'Ly', Ly, 'M', M, 'dofs', info.dofs, ...
        'Mx', Mx, 'My', My, 'n_matched', n_matched, ...
        'n_cells', numel(matched), 'n_computed', numel(lambda_num), ...
        'n_unmatched', n_unmatched);

    % --- 4. Print the table, matched cells in bold ----------------------
    print_table(lambda_tab, matched, mm, nn);

    fprintf('\nMatched %d of %d table cells to computed eigenvalues.\n', ...
        n_matched, numel(matched));
    fprintf('Computed eigenvalues: %d total, %d unmatched.\n', ...
        numel(lambda_num), n_unmatched);
    if n_unmatched > 0
        warning('eigenvalues_rectangle_match:unmatched', ...
            ['%d computed eigenvalues did not match any (m, n) cell; ', ...
             'increase margin so the table covers all resolved modes.'], ...
            n_unmatched);
    end

    % --- 5. Save the table to results/ as markdown ----------------------
    out_dir = fullfile(project_root, 'results', 'eigenvalues_indexing');
    if ~exist(out_dir, 'dir')
        mkdir(out_dir);
    end
    md_file = fullfile(out_dir, sprintf('rectangle_match_M%d.md', M));
    write_markdown(md_file, lambda_tab, matched, mm, nn, meta);
    fprintf('Wrote %s\n', md_file);
end


function print_table(lambda_tab, matched, mm, nn)
%PRINT_TABLE Print lambda_tab indexed by m (rows) and n (cols); matched bold.
    BOLD  = [char(27) '[1m'];
    RESET = [char(27) '[0m'];

    field = 9;                              % column width for each value
    label = 6;                              % width of the row-label column
    fmt   = sprintf('%%%d.2f', field);      % e.g. '%9.2f'

    % Header: n indices across the top.
    fprintf('%*s |', label, 'm \ n');
    for n = nn
        fprintf('%*d', field, n);
    end
    fprintf('\n');
    fprintf('%s\n', repmat('-', 1, label + 2 + field * numel(nn)));

    % One row per m.
    for r = 1:numel(mm)
        fprintf('%*d |', label, mm(r));
        for c = 1:numel(nn)
            cell = sprintf(fmt, lambda_tab(r, c));
            if matched(r, c)
                fprintf('%s%s%s', BOLD, cell, RESET);
            else
                fprintf('%s', cell);
            end
        end
        fprintf('\n');
    end
end


function write_markdown(md_file, lambda_tab, matched, mm, nn, meta)
%WRITE_MARKDOWN Write the (m, n) eigenvalue table as markdown; matched in bold.
%   The matched cells are wrapped in **...** so they render bold, mirroring the
%   terminal output of PRINT_TABLE.
    fid = fopen(md_file, 'w');
    if fid == -1
        error('eigenvalues_rectangle_match:cannotOpen', ...
            'Could not open %s for writing.', md_file);
    end
    closer = onCleanup(@() fclose(fid));

    fprintf(fid, '# Rectangle DST eigenvalue match\n\n');
    fprintf(fid, ['Full DST-Laplacian spectrum of the rectangle ', ...
        '$[0, %s] \\times [0, %s]$ at resolution $M = %d$ ', ...
        '(dofs $= %d$), matched against the analytic Dirichlet eigenvalues\n\n'], ...
        pi_label(meta.Lx), pi_label(meta.Ly), meta.M, meta.dofs);
    fprintf(fid, ['$$\\lambda_{m,n} = (m\\pi/L_x)^2 + (n\\pi/L_y)^2 ', ...
        '= m^2/4 + n^2, \\qquad m, n = 1, 2, \\dots$$\n\n']);
    fprintf(fid, ['The grid resolves $M_x = %d$ modes in $x$ and ', ...
        '$M_y = %d$ modes in $y$. Cells matched to a computed eigenvalue ', ...
        '(to round-off) are shown in **bold**; the unresolved border ', ...
        '($m > M_x$ or $n > M_y$) is in normal weight. Rows are indexed by ', ...
        '$m$, columns by $n$.\n\n'], meta.Mx, meta.My);

    % Header row: n indices.
    fprintf(fid, '| $m \\backslash n$ |');
    for n = nn
        fprintf(fid, ' %d |', n);
    end
    fprintf(fid, '\n');

    % Alignment row: left-aligned label column, right-aligned value columns.
    fprintf(fid, '|---|');
    for c = 1:numel(nn)
        fprintf(fid, '--:|');
    end
    fprintf(fid, '\n');

    % One row per m.
    for r = 1:numel(mm)
        fprintf(fid, '| %d |', mm(r));
        for c = 1:numel(nn)
            if matched(r, c)
                fprintf(fid, ' **%.2f** |', lambda_tab(r, c));
            else
                fprintf(fid, ' %.2f |', lambda_tab(r, c));
            end
        end
        fprintf(fid, '\n');
    end

    fprintf(fid, ['\nMatched %d of %d table cells to computed eigenvalues. ', ...
        'Computed eigenvalues: %d total, %d unmatched.\n'], ...
        meta.n_matched, meta.n_cells, meta.n_computed, meta.n_unmatched);
end


function s = pi_label(v)
%PI_LABEL LaTeX label for a length that is an integer multiple of pi.
%   Renders pi as "\pi" and k*pi as "k\pi"; falls back to a decimal otherwise.
    k = v / pi;
    if abs(k - round(k)) < 1e-9
        k = round(k);
        if k == 1
            s = '\pi';
        else
            s = sprintf('%d\\pi', k);
        end
    else
        s = sprintf('%.4f', v);
    end
end
