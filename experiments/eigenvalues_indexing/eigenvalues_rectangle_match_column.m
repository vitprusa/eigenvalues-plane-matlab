function eigenvalues_rectangle_match_column(M, margin)
%EIGENVALUES_RECTANGLE_MATCH_COLUMN Per-position column table of the rectangle match.
%
%   eigenvalues_rectangle_match_column()         uses M = 19 and a default margin.
%   eigenvalues_rectangle_match_column(M)        uses resolution M.
%   eigenvalues_rectangle_match_column(M, margin) lists margin extra positions
%                                          past the last resolved eigenvalue.
%
%   Companion to EIGENVALUES_RECTANGLE_MATCH and EIGENVALUES_RECTANGLE_ORDER.
%   Same set-up: the Dirichlet-Laplacian on the 2:1 catalog rectangle
%   [0, 2*pi] x [0, pi] has the exact eigenvalues
%
%       lambda_{m,n} = (m*pi/Lx)^2 + (n*pi/Ly)^2 = m^2/4 + n^2,   m, n = 1, 2, ...
%
%   Where the sibling scripts lay the spectrum out on the (m, n) lattice, this
%   one unrolls it into a single sequence ordered by magnitude and prints one
%   row per position. The four columns are
%
%       1. position  -- rank of lambda_{m,n} in the magnitude-ordered sequence
%                       of all analytic eigenvalues (1 = smallest),
%       2. (m, n)    -- the index pair attaining that eigenvalue,
%       3. analytic  -- the analytic eigenvalue lambda_{m,n}, and
%       4. computed  -- the DST eigenvalue matched to it, or "--" if the grid
%                       does not resolve that mode (m > Mx or n > My).
%
%   The table runs from position 1 to (last resolved position) + margin, so it
%   contains every resolved (matched) eigenvalue plus a margin of trailing
%   unresolved ones. Because the DST grid resolves a rectangular Mx-by-My block
%   rather than the leading eigenvalues, the matched rows are interleaved with
%   "--" rows: some unresolved border modes outrank resolved ones.
%
%   With equal grid spacing in x and y, the top edge y = pi only lands on a
%   grid line when M+1 is even, i.e. M is odd; the default M = 19 is the odd
%   value closest to 20. The grid then resolves Mx = M modes in x and
%   My = (M+1)/2 - 1 modes in y. Change Lx, Ly below for another rectangle
%   (and pick M so both edges stay on the grid).
%
%   See also EIGENVALUES_RECTANGLE_MATCH, EIGENVALUES_RECTANGLE_ORDER,
%   MAKE_DST_LAPLACE_MAT_BATCHED, DOMAIN_CATALOG_DST.
%
%   Generated by Claude (Claude Opus 4.8, model ID claude-opus-4-8).

    if nargin < 1 || isempty(M)
        M = 19;
    end
    if nargin < 2 || isempty(margin)
        margin = 11;
    end

    % This file lives in experiments/eigenvalues_indexing/; put the project
    % sources on the path.
    script_dir      = fileparts(mfilename('fullpath'));
    experiments_dir = fileparts(script_dir);
    project_root    = fileparts(experiments_dir);
    run(fullfile(project_root, 'startup.m'));

    % 2:1 catalog rectangle [0, Lx] x [0, Ly]. Analytic spectrum is
    % lambda_{m,n} = (m*pi/Lx)^2 + (n*pi/Ly)^2 = m^2/4 + n^2.
    Lx = 2 * pi;
    Ly = pi;

    % --- 1. Computed full spectrum at resolution M -----------------------
    [x_range, y_range] = bounding_box(0, Lx, 0, Ly);
    phi = @(x, y) indicator_rectangle(x, y, 0, Lx, 0, Ly);
    [L, info] = make_dst_laplace_mat_batched(x_range, y_range, M, phi);
    % lambda_num = sort(-real(eig(L)), 'ascend');   % positive, ascending
    % positive, ascending
    lambda_num = sort(-eig(dst_laplace_symmetrise(L)), 'ascend');

    % Modes resolved per direction = interior grid points per direction. For a
    % rectangle filling its box this is the full grid minus the two boundary
    % lines. Guard against a domain whose edges miss the grid.
    Mx = numel(info.x_vec) - 2;
    My = numel(info.y_vec) - 2;
    if Mx * My ~= info.dofs
        error('eigenvalues_rectangle_match_column:misaligned', ...
            ['Grid does not cleanly resolve the rectangle (Mx*My = %d, ', ...
             'dofs = %d). Pick M so both edges land on grid lines ', ...
             '(M odd for the 2:1 rectangle).'], Mx * My, info.dofs);
    end

    fprintf('Rectangle [0, %.4f] x [0, %.4f], M = %d, dofs = %d (Mx = %d, My = %d)\n', ...
        Lx, Ly, M, info.dofs, Mx, My);

    % --- 2. Magnitude-ordered analytic sequence -------------------------
    % Order all analytic eigenvalues; the corner (Mx, My) carries the largest
    % eigenvalue of the resolved block, so its rank R is the last resolved
    % position. List positions 1 .. R + margin.
    seq = ordered_eigenvalues(Lx, Ly, 4 * Mx * My + margin + 50);
    R   = find(seq(:, 1) == Mx & seq(:, 2) == My, 1);   % rank of corner mode
    K   = R + margin;
    if K > size(seq, 1)
        seq = ordered_eigenvalues(Lx, Ly, K);
    end
    seq = seq(1:K, :);                                   % columns [m, n, lambda]

    % --- 3. Match computed eigenvalues to the resolved rows -------------
    % Greedy, multiplicity-aware matching by value; resolved cells (m <= Mx,
    % n <= My) are visited first so they claim their computed eigenvalue ahead
    % of any coincident out-of-grid cell of equal value.
    resolved    = seq(:, 1) <= Mx & seq(:, 2) <= My;
    matched_val = nan(K, 1);
    used        = false(numel(lambda_num), 1);
    reltol      = 1e-6;
    visit       = [find(resolved); find(~resolved)];
    for i = visit'
        target = seq(i, 3);
        cand   = find(~used & abs(lambda_num - target) <= reltol * target, 1);
        if ~isempty(cand)
            used(cand)     = true;
            matched_val(i) = lambda_num(cand);
        end
    end
    matched     = ~isnan(matched_val);
    n_matched   = nnz(matched);
    n_unmatched = nnz(~used);

    % --- 4. First-unmatched index: observed vs closed form --------------
    % The first '--' row is the smallest analytic eigenvalue with no DST
    % counterpart. Its position has a closed form (see FIRST_UNMATCHED_INDEX);
    % recompute it independently and check the two agree, so the table doubles
    % as a test of the formula.
    [idx_pred, ms, ns, lstar] = first_unmatched_index(Mx, My, Lx, Ly);
    idx_obs = find(~matched, 1);     % position of first '--' in the window

    meta = struct('Lx', Lx, 'Ly', Ly, 'M', M, 'dofs', info.dofs, ...
        'Mx', Mx, 'My', My, 'n_matched', n_matched, ...
        'n_rows', K, 'n_computed', numel(lambda_num), ...
        'n_unmatched', n_unmatched, 'idx_pred', idx_pred, ...
        'idx_obs', idx_obs, 'ms', ms, 'ns', ns, 'lstar', lstar);

    % --- 5. Print the column table, matched rows in bold ----------------
    print_table(seq, matched, matched_val);
    fprintf('\nListed positions 1..%d; %d resolved (matched), %d unresolved (--).\n', ...
        K, n_matched, K - n_matched);
    fprintf('Computed eigenvalues: %d total, %d unmatched.\n', ...
        numel(lambda_num), n_unmatched);

    fprintf(['First unmatched: position %d, mode (m, n) = (%d, %d), ', ...
        'lambda* = %.4f. Closed form predicts position %d -- %s.\n'], ...
        idx_obs, ms, ns, lstar, idx_pred, ...
        check_tag(isequal(idx_obs, idx_pred)));
    if ~isequal(idx_obs, idx_pred)
        warning('eigenvalues_rectangle_match_column:indexmismatch', ...
            ['Observed first-unmatched position %d disagrees with the ', ...
             'closed form %d.'], idx_obs, idx_pred);
    end
    if n_unmatched > 0
        warning('eigenvalues_rectangle_match_column:unmatched', ...
            ['%d computed eigenvalues did not match any listed position; ', ...
             'increase margin so the table covers all resolved modes.'], ...
            n_unmatched);
    end

    % --- 6. Save the column table to results/ as markdown ---------------
    out_dir = fullfile(project_root, 'results', 'eigenvalues_indexing');
    if ~exist(out_dir, 'dir')
        mkdir(out_dir);
    end
    md_file = fullfile(out_dir, sprintf('rectangle_match_column_M%d.md', M));
    write_markdown(md_file, seq, matched, matched_val, meta);
    fprintf('Wrote %s\n', md_file);
end


function seq = ordered_eigenvalues(Lx, Ly, need)
%ORDERED_EIGENVALUES Leading analytic eigenvalues, magnitude-ordered.
%   Returns an N-by-3 matrix [m, n, lambda] sorted by lambda ascending, whose
%   first `need` rows are guaranteed correctly ordered against the full
%   spectrum. A lattice 1..Mmax x 1..Nmax contains every eigenvalue up to
%   B = min((Mmax+1)*pi/Lx)^2 + (pi/Ly)^2, (pi/Lx)^2 + ((Nmax+1)*pi/Ly)^2),
%   the smallest eigenvalue of any mode it omits; rows with lambda <= B are
%   therefore reliably the leading spectrum. Grow the lattice until at least
%   `need` rows are reliable.
    Mmax = 8;
    Nmax = 8;
    while true
        [Mr, Nr] = ndgrid(1:Mmax, 1:Nmax);
        val = (Mr * pi / Lx).^2 + (Nr * pi / Ly).^2;
        B   = min(((Mmax + 1) * pi / Lx)^2 + (pi / Ly)^2, ...
                  (pi / Lx)^2 + ((Nmax + 1) * pi / Ly)^2);

        % Sort by magnitude; round first so degenerate eigenvalues tie exactly
        % (smallest spacing is 1/4), then break ties by (m, n) for determinism.
        keys = sortrows([round(val(:), 9), Mr(:), Nr(:)]);
        reliable = keys(keys(:, 1) <= B + 1e-9, :);
        if size(reliable, 1) >= need
            m = reliable(1:need, 2);
            n = reliable(1:need, 3);
            lambda = (m * pi / Lx).^2 + (n * pi / Ly).^2;
            seq = [m, n, lambda];
            return
        end
        Mmax = 2 * Mmax;
        Nmax = 2 * Nmax;
    end
end


function [idx, ms, ns, lstar] = first_unmatched_index(Mx, My, Lx, Ly)
%FIRST_UNMATCHED_INDEX Closed-form position of the first unmatched eigenvalue.
%   The DST grid resolves the block 1 <= m <= Mx, 1 <= n <= My, so the first
%   analytic eigenvalue with no computed counterpart is the smallest one of any
%   unresolved mode (m > Mx or n > My). That minimum is attained by stepping
%   one index past either resolution limit -- (1, My+1) or (Mx+1, 1) -- and its
%   position in the magnitude-ordered spectrum is one past the count of strictly
%   smaller eigenvalues (every one of which is resolved, hence matched). For
%   the 2:1 rectangle this reduces to
%   idx = 1 + sum_{n=1}^{My} floor(sqrt((M+1)^2 - 4 n^2)).
    cand   = [1, My + 1; Mx + 1, 1];
    cval   = (cand(:, 1) * pi / Lx).^2 + (cand(:, 2) * pi / Ly).^2;
    [lstar, k] = min(cval);
    ms = cand(k, 1);
    ns = cand(k, 2);

    % Count analytic modes (m, n >= 1) with lambda strictly below lstar. The
    % first unmatched mode has m = 1 (the y-step always wins for the 2:1
    % rectangle), so it sorts ahead of any equal-value resolved mode and the
    % index is exactly count + 1.
    tol  = 1e-9;
    cnt  = 0;
    nmax = floor((Ly / pi) * sqrt(lstar));        % (n*pi/Ly)^2 < lstar
    for n = 1:nmax
        rem = lstar - (n * pi / Ly)^2;
        if rem > 0
            cnt = cnt + floor((Lx / pi) * sqrt(rem) - tol);   % m >= 1
        end
    end
    idx = cnt + 1;
end


function s = check_tag(ok)
%CHECK_TAG 'PASS'/'FAIL' label for the index self-check.
    if ok
        s = 'PASS';
    else
        s = 'FAIL';
    end
end


function print_table(seq, matched, matched_val)
%PRINT_TABLE Print the four-column position table; matched rows in bold.
    BOLD  = [char(27) '[1m'];
    RESET = [char(27) '[0m'];

    header = sprintf('%6s  %-10s  %12s  %14s', ...
        'pos', '(m, n)', 'analytic', 'computed');
    fprintf('\n%s\n', header);
    fprintf('%s\n', repmat('-', 1, numel(header)));

    for p = 1:size(seq, 1)
        m   = seq(p, 1);
        n   = seq(p, 2);
        idx = sprintf('(%d, %d)', m, n);             % (m, n), as in the siblings
        if matched(p)
            num = sprintf('%14.6f', matched_val(p));
        else
            num = sprintf('%14s', '--');
        end
        row = sprintf('%6d  %-10s  %12.2f  %s', p, idx, seq(p, 3), num);
        if matched(p)
            fprintf('%s%s%s\n', BOLD, row, RESET);
        else
            fprintf('%s\n', row);
        end
    end
end


function write_markdown(md_file, seq, matched, matched_val, meta)
%WRITE_MARKDOWN Write the four-column position table as markdown; matched bold.
    fid = fopen(md_file, 'w');
    if fid == -1
        error('eigenvalues_rectangle_match_column:cannotOpen', ...
            'Could not open %s for writing.', md_file);
    end
    closer = onCleanup(@() fclose(fid));

    fprintf(fid, '# Rectangle DST eigenvalue match (column form)\n\n');
    fprintf(fid, ['Full DST-Laplacian spectrum of the rectangle ', ...
        '$[0, %s] \\times [0, %s]$ at resolution $M = %d$ (dofs $= %d$), ', ...
        'unrolled into the magnitude-ordered sequence of the analytic ', ...
        'Dirichlet eigenvalues\n\n'], ...
        pi_label(meta.Lx), pi_label(meta.Ly), meta.M, meta.dofs);
    fprintf(fid, ['$$\\lambda_{m,n} = (m\\pi/L_x)^2 + (n\\pi/L_y)^2 ', ...
        '= m^2/4 + n^2, \\qquad m, n = 1, 2, \\dots$$\n\n']);
    fprintf(fid, ['The grid resolves $M_x = %d$ modes in $x$ and ', ...
        '$M_y = %d$ modes in $y$. Each row is one position in the ordered ', ...
        'sequence: its **position** (rank, 1 = smallest), the index pair ', ...
        '$(m, n)$ attaining it, the analytic eigenvalue, and the computed ', ...
        'DST eigenvalue matched to it (`--` where the grid does not resolve ', ...
        'that mode, i.e. $m > M_x$ or $n > M_y$). Matched rows are in ', ...
        '**bold**. The table runs to the last resolved position plus a ', ...
        'margin, so matched rows are interleaved with `--`: some unresolved ', ...
        'border modes outrank resolved ones.\n\n'], meta.Mx, meta.My);

    fprintf(fid, '| position | $(m, n)$ | analytic $\\lambda$ | computed $\\lambda$ |\n');
    fprintf(fid, '|--:|:--:|--:|--:|\n');
    for p = 1:size(seq, 1)
        m = seq(p, 1);
        n = seq(p, 2);
        if matched(p)
            fprintf(fid, '| **%d** | **(%d, %d)** | **%.2f** | **%.6f** |\n', ...
                p, m, n, seq(p, 3), matched_val(p));
        else
            fprintf(fid, '| %d | (%d, %d) | %.2f | -- |\n', p, m, n, seq(p, 3));
        end
    end

    fprintf(fid, ['\nListed positions 1..%d; %d resolved (matched), ', ...
        '%d unresolved (`--`). Computed eigenvalues: %d total, %d unmatched.\n'], ...
        meta.n_rows, meta.n_matched, meta.n_rows - meta.n_matched, ...
        meta.n_computed, meta.n_unmatched);

    if isequal(meta.idx_obs, meta.idx_pred), tag = 'PASS'; else, tag = 'FAIL'; end
    fprintf(fid, ['\nFirst unmatched eigenvalue: position %d, mode ', ...
        '$(m, n) = (%d, %d)$, $\\lambda^\\* = %.4f$. The closed form ', ...
        'predicts position %d (**%s**).\n'], ...
        meta.idx_obs, meta.ms, meta.ns, meta.lstar, meta.idx_pred, tag);
end


function s = pi_label(v)
%PI_LABEL LaTeX label for a length that is an integer multiple of pi.
%   Renders pi as "\pi" and k*pi as "k\pi"; falls back to a decimal otherwise.
    k = v / pi;
    if abs(k - round(k)) < 1e-9
        k = round(k);
        if k == 1
            s = '\pi';
        else
            s = sprintf('%d\\pi', k);
        end
    else
        s = sprintf('%.4f', v);
    end
end
