function floor_value = reference_floor(runs, ref_dofs)
%REFERENCE_FLOOR What the reference itself cannot resolve.
%
%   The error of the finest DST run of the sweep. It is measured against the
%   reference, which is a DST run one resolution finer, so what it reports is
%   how far the two of them are apart rather than how far either is from the
%   exact eigenvalues. An error of that size, or a tolerance asked for within an
%   order of magnitude of it, says nothing.
%
%   Against a closed form there is no floor at all: REF_DOFS is 0, every error in
%   the table is a true error, and NaN comes back so that no floor is drawn in
%   the figure and none is warned about in the answer table.
    if ref_dofs == 0
        floor_value = NaN;
        return;
    end
    dst = strcmp({runs.method}, 'DST');
    if ~any(dst)
        floor_value = NaN;
        return;
    end
    dst_runs = runs(dst);
    [~, imax] = max([dst_runs.dofs]);
    floor_value = dst_runs(imax).max_rel_err;
end


function answer = required_dofs(runs, tolerances, n)
%REQUIRED_DOFS The dof count each method needs, per tolerance.
%
%   MEASURED where the sweep reaches the tolerance: the coarsest run from which
%   the curve stays under it, the tail being taken as a whole so that a single
%   lucky point below the level does not count as convergence.
%
%   FITTED where it does not: E ~ C * dofs^p over the finest runs of the method,
%   and the crossing of the level read off the fit. The rate is what a
%   discretisation of a given order gives on this domain -- for a second-order
%   method with dofs ~ h^-2 in the plane, p = -1 -- so the extrapolation carries
%   as far as the rate holds, and no further.
%
%   The timing is the cost of the run that carries the answer: the measured one
%   where the sweep reaches the tolerance, and otherwise the same extrapolation
%   applied to the timings, time ~ C * dofs^q over the same finest runs. Every
%   run here is a dense eig, whose cost grows as the cube of the dof count and
%   whose matrix is stored in full, so an extrapolated timing says what the
%   answer would cost by this route rather than what it need cost by any route.
    methods = {method_styles().name};
    n_fit = 4;
    answer = struct('method', {}, 'tolerance', {}, 'dofs', {}, 'source', {}, ...
                    'rate', {}, 'per_eigenvalue', {}, 'time', {}, 'time_source', {});
    for mi = 1:numel(methods)
        [d, e, t] = curve(runs, methods{mi});
        if isempty(d)
            continue;
        end
        take = max(1, numel(d) - n_fit + 1) : numel(d);
        if numel(take) >= 2
            p = polyfit(log(d(take)), log(e(take)), 1);
            q = polyfit(log(d(take)), log(t(take)), 1);
        else
            p = [NaN NaN];
            q = [NaN NaN];
        end
        for ti = 1:numel(tolerances)
            tol = tolerances(ti);
            below = e <= tol;
            if below(end)
                first = find(~below, 1, 'last') + 1;
                if isempty(first); first = 1; end
                required = d(first);
                source = 'measured';
                rate = NaN;
                tsec = t(first);
                time_source = 'measured';
            elseif isfinite(p(1)) && p(1) < 0
                required = exp((log(tol) - p(2)) / p(1));
                source = 'fitted';
                rate = p(1);
                tsec = exp(polyval(q, log(required)));
                time_source = 'fitted';
            else
                required = NaN;
                source = 'unreached';
                rate = NaN;
                tsec = NaN;
                time_source = 'unreached';
            end
            answer(end+1) = struct('method', methods{mi}, 'tolerance', tol, ...
                'dofs', required, 'source', source, 'rate', rate, ...
                'per_eigenvalue', required / n, 'time', tsec, ...
                'time_source', time_source); %#ok<AGROW>
        end
    end
end


function report_answer(cfg, n, answer, floor_value, ref_dofs)
%REPORT_ANSWER The answer table, printed.
    fprintf('\n');
    fprintf('  Degrees of freedom needed for the first %d eigenvalues, %s domain\n', ...
            n, cfg.pretty);
    if ref_dofs == 0
        fprintf('  (reference: the closed form; every error below is a true error)\n\n');
    else
        fprintf('  (reference: DST at %d dofs; it resolves errors down to %.1e)\n\n', ...
                ref_dofs, floor_value);
    end
    fprintf('    %-5s %10s %12s %8s %11s %8s %10s\n', ...
            'meth', 'tolerance', 'dofs', 'per eig', 'from', 'rate', 'dense eig');
    for i = 1:numel(answer)
        a = answer(i);
        if isnan(a.dofs)
            fprintf('    %-5s %9.2g%% %12s %8s %11s %8s %10s\n', ...
                    a.method, 100 * a.tolerance, '--', '--', a.source, '--', '--');
            continue;
        end
        if isnan(a.rate)
            rate = '--';
        else
            rate = sprintf('%.2f', a.rate);
        end
        fprintf('    %-5s %9.2g%% %12s %8.1f %11s %8s %10s\n', ...
                a.method, 100 * a.tolerance, round_dofs(a.dofs, a.source), ...
                a.per_eigenvalue, a.source, rate, format_time(a.time));
    end
    fprintf('\n');
    fprintf(['  "dense eig" is the cost of that one run on this machine, measured\n', ...
             '  where the dof count is and extrapolated with it where it is not.\n\n']);
    if any(cellfun(@(s) strcmp(s, 'unreached'), {answer.source}))
        fprintf('  "unreached": the sweep stays above the tolerance and the error\n');
        fprintf('  does not fall off as a power law, so there is nothing to fit.\n\n');
    end
    tight = unique([answer.tolerance]);
    tight = tight(tight < 10 * floor_value);
    for t = tight
        fprintf(['  The %g%% row is within an order of magnitude of the reference ', ...
                 'floor\n  %.1e, and the DST rows of it are self-consistency ', ...
                 'rather than error.\n\n'], 100 * t, floor_value);
    end
end


function time_label(ax, x, y, tsec, color, place)
%TIME_LABEL What one run cost, written beside its marker.
%
%   PLACE is the compass direction the label takes from the marker, in the colour
%   of its own curve. One direction per method rather than one per point, so that
%   the eye learns where to look once: FD to the north-east, DST and FEM to the
%   south-west.
%
%   Small, and out of the legend: the labels are there to be read off a point
%   once the eye has found it, not to be scanned as a series.
    if isnan(tsec)
        return;
    end
    switch place
        case 'NE'
            x_text = x * 1.04; y_text = y * 1.18;
            halign = 'left';   valign = 'bottom';
        case 'SW'
            x_text = x * 0.96; y_text = y * 0.85;
            halign = 'right';  valign = 'top';
        otherwise
            error('eigenvalues_dof_requirement:place', ...
                'Label direction must be "NE" or "SW", got "%s".', place);
    end
    text(ax, x_text, y_text, format_time(tsec), ...
        'Color', color, 'FontSize', 9, 'HandleVisibility', 'off', ...
        'HorizontalAlignment', halign, 'VerticalAlignment', valign);
end


function s = format_time(tsec)
%FORMAT_TIME A duration in the unit that reads, to two significant figures.
    if isnan(tsec)
        s = '--';
    elseif tsec < 1
        % Two significant figures, not one decimal: the symmetrised eig put the
        % coarse DST runs below a twentieth of a second, where "0.0 s" is all a
        % single decimal has left to say.
        s = sprintf('%.2g s', tsec);
    elseif tsec < 90
        s = sprintf('%.1f s', tsec);
    elseif tsec < 5400
        s = sprintf('%.1f min', tsec / 60);
    elseif tsec < 1.728e5
        s = sprintf('%.1f h', tsec / 3600);
    else
        s = sprintf('%.1f d', tsec / 86400);
    end
end


function s = round_dofs(d, source)
%ROUND_DOFS A dof count printed to the precision it carries.
%
%   A measured count is a run of the sweep and is printed as it is; a fitted one
%   is worth three significant figures.
    if strcmp(source, 'measured')
        s = sprintf('%d', round(d));
    else
        s = sprintf('%.0f', round(d, 3, 'significant'));
    end
end


