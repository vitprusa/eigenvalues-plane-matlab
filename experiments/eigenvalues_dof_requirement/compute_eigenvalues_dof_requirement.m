function [runs, ref_dofs] = read_runs_csv(csv)
%READ_RUNS_CSV Read back a run table written by WRITE_RUNS_CSV.
%
%   REF_DOFS is the reference the table was measured against, taken from the
%   header, so that the caller can tell whether the table still applies.
    fid = fopen(csv, 'r');
    if fid == -1
        error('eigenvalues_dof_requirement:csvread', 'Could not open %s.', csv);
    end
    closer = onCleanup(@() fclose(fid)); %#ok<NASGU>
    runs = empty_runs();
    ref_dofs = NaN;
    while true
        line = fgetl(fid);
        if ~ischar(line); break; end
        s = strtrim(line);
        if ~isempty(s) && s(1) == '#'
            tok = regexp(s, '^#\s*Reference:.*dofs\s*=\s*(\d+)', 'tokens', 'once');
            if ~isempty(tok); ref_dofs = str2double(tok{1}); end
            continue;
        end
        if isempty(s) || strncmpi(s, 'method,', 7); continue; end
        p = strsplit(s, ',');
        if numel(p) < 7; continue; end
        runs(end+1) = mk(p{1}, p{2}, str2double(p{3}), str2double(p{4}), ...
                         str2double(p{5}), str2double(p{6}), str2double(p{7})); %#ok<AGROW>
    end
end


