function [d, e, t] = curve(runs, method)
%CURVE Sorted dof count, largest relative error and timing of one method.
    sel = strcmp({runs.method}, method);
    d = [runs(sel).dofs];
    e = [runs(sel).max_rel_err];
    t = [runs(sel).time];
    [d, ord] = sort(d);
    e = e(ord);
    t = t(ord);
    keep = e > 0;            % belt and braces: no zero can reach a log axis
    d = d(keep); e = e(keep); t = t(keep);
end


