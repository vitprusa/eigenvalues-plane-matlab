function plot_requirement(stem, runs, answer, tolerances, n, floor_value, ref_label)
%PLOT_REQUIREMENT The largest error over the block against DOF, on log-log axes.
%
%   One curve per method, drawn over the runs of the sweep, and continued as a
%   dotted line along the fit wherever the answer had to be extrapolated. The
%   tolerances are drawn as levels, so the answer is where a curve crosses one.
%   Colours and markers are those of the convergence figures, so that the
%   figures of a domain read as one family.
%
%   Every marker carries what that run cost, in the units of FORMAT_TIME, which
%   is what the answer table prints. The accuracy of a method is only half the
%   question here and the figure would otherwise answer it alone: two methods
%   reaching a tolerance at the same dof count are not equally cheap, the dense
%   eig of the same matrix taking DST a fraction of what it takes FD. The label
%   on an extrapolated marker is extrapolated too, along time ~ dofs^q.
    styles  = method_styles();
    methods = {styles.name};
    colors  = {styles.color};
    markers = {styles.marker};
    places  = {styles.place};

    % Render all text with the LaTeX interpreter, as in the other figures.
    fig = figure('Visible', 'off', 'Position', [100 100 950 680], ...
        'defaultAxesTickLabelInterpreter', 'latex', ...
        'defaultTextInterpreter',          'latex', ...
        'defaultLegendInterpreter',        'latex');
    ax = axes(fig);
    hold(ax, 'on');

    tol_min = min(tolerances);
    d_lo = inf;
    d_hi = 0;
    for mi = 1:numel(methods)
        [d, e, t] = curve(runs, methods{mi});
        if isempty(d); continue; end
        loglog(ax, d, e, ['-' markers{mi}], 'Color', colors{mi}, 'LineWidth', 2.0, ...
            'MarkerSize', 7, 'MarkerFaceColor', 'w', ...
            'DisplayName', sprintf('$\\mathtt{%s}$', methods{mi}));
        for j = 1:numel(d)
            time_label(ax, d(j), e(j), t(j), colors{mi}, places{mi});
        end
        d_lo = min(d_lo, min(d));
        d_hi = max(d_hi, max(d));

        % The extrapolation, where the answer rests on one: from the finest run
        % along the fit to the tightest tolerance asked for.
        fitted = strcmp({answer.method}, methods{mi}) & ...
                 strcmp({answer.source}, 'fitted');
        if any(fitted)
            target = answer(find(fitted, 1, 'last'));
            if isfinite(target.dofs)
                % Along the fit itself, so that the line ends on the marker that
                % sits at the answer.
                dd = logspace(log10(max(d)), log10(target.dofs), 50);
                ee = tol_min * (dd / target.dofs).^target.rate;
                loglog(ax, dd, ee, ':', 'Color', colors{mi}, 'LineWidth', 1.5, ...
                    'HandleVisibility', 'off');
                loglog(ax, target.dofs, tol_min, markers{mi}, 'Color', colors{mi}, ...
                    'MarkerSize', 9, 'MarkerFaceColor', colors{mi}, ...
                    'HandleVisibility', 'off');
                time_label(ax, target.dofs, tol_min, target.time, ...
                           colors{mi}, places{mi});
                d_hi = max(d_hi, target.dofs);
            end
        end
    end

    for ti = 1:numel(tolerances)
        yline(ax, tolerances(ti), 'k--', sprintf('$%g\\,\\%%$', 100 * tolerances(ti)), ...
            'LineWidth', 1.0, 'Interpreter', 'latex', ...
            'LabelHorizontalAlignment', 'left', 'HandleVisibility', 'off');
    end
    if isfinite(floor_value) && floor_value > 0
        h = yline(ax, floor_value, '-');
        set(h, 'Color', [0.6 0.6 0.6], 'LineWidth', 1.0, ...
               'DisplayName', 'reference floor');
    end

    hold(ax, 'off');
    set(ax, 'XScale', 'log', 'YScale', 'log');
    % Room on the right for the timing label of the last marker.
    xlim(ax, [d_lo * 0.8, d_hi * 2.4]);
    xlabel(ax, 'degrees of freedom');
    % The reference is named on the axis: on a domain with a closed form these
    % are true errors, and the label has to say so rather than claim a DST run
    % the computation never made.
    ylabel(ax, sprintf(['$\\max_{k \\leq %d} \\frac{|\\lambda_k - ', ...
                        '\\lambda_k^{\\mathtt{%s}}|}{\\lambda_k^{\\mathtt{%s}}}$'], ...
                       n, ref_label, ref_label), 'FontSize', 16);
    % No title: the domain is identified by the output file name.
    legend(ax, 'Location', 'southwest', 'FontSize', 10, 'Box', 'off');
    grid(ax, 'on'); box(ax, 'on');
    set(ax, 'FontSize', 12);

    eps_file = [stem '.eps'];
    try
        exportgraphics(fig, eps_file, 'ContentType', 'vector');
    catch
        print(fig, eps_file, '-depsc2', '-painters');
    end
    fprintf('  Wrote %s\n', eps_file);
    close(fig);
end
